"""The record of a deployment, as the modules speak of it — plain Python: a row of Camtrap DP's "deployments" table, by what it holds. The domains and
the use cases of the deployments and the uploaders take one by this; what is handed to them is shared.camtrap.DeploymentFields, which Pydantic
checks at the edge, and which keeps to it.

    >>> from wildintel_uploader.shared.camtrap import DeploymentFields
    >>> record: DeploymentRecord = DeploymentFields(deployment_id="R0001-DONA_01", latitude=37.0, longitude=-6.4,
    ...                                             start_date="2026-03-01T10:00:00Z", end_date="2026-04-01T10:00:00Z")
    >>> record.deployment_id
    'R0001-DONA_01'
"""
from __future__ import annotations

from typing import Protocol


class DeploymentRecord(Protocol):
    """A deployment of Camtrap DP (deploymentID -> deployment_id…): where, when, with what camera, set how. Read only."""

    @property
    def deployment_id(self) -> str: ...
    @property
    def location_id(self) -> str | None: ...
    @property
    def location_name(self) -> str | None: ...
    @property
    def latitude(self) -> float: ...
    @property
    def longitude(self) -> float: ...
    @property
    def coordinate_uncertainty(self) -> int | None: ...
    @property
    def start_date(self) -> str: ...            # ISO 8601 with its timezone designator
    @property
    def end_date(self) -> str: ...
    @property
    def setup_by(self) -> str | None: ...
    @property
    def camera_id(self) -> str | None: ...
    @property
    def camera_model(self) -> str | None: ...
    @property
    def camera_interval(self) -> int | None: ...
    @property
    def camera_height(self) -> float | None: ...
    @property
    def camera_depth(self) -> float | None: ...
    @property
    def camera_tilt(self) -> int | None: ...
    @property
    def camera_heading(self) -> int | None: ...
    @property
    def detection_distance(self) -> float | None: ...
    @property
    def timestamp_issues(self) -> bool | None: ...
    @property
    def bait_use(self) -> bool | None: ...
    @property
    def feature_type(self) -> str | None: ...
    @property
    def habitat(self) -> str | None: ...
    @property
    def deployment_groups(self) -> str | None: ...
    @property
    def comments(self) -> str | None: ...
    @property
    def tags(self) -> list[str]: ...
